#!/usr/bin/env python3
"""Build creature-card assets + shared/creatures.js.

Usage: python3 -I scripts/build-creatures.py <set dir>
<set dir> = the unpacked «Набір_300_карток» folder: manifest_*.csv, «Українські/» and «Español/» with
NNN_<name>_01_<front>.png and NNN_<name>_02_<back>.png (1024x1536). Images go to images/creatures/<lang>/:
c001.webp (front), c001-b.webp (back, full size: its text must stay readable), thumb/c001.webp.
"""
import csv
import glob
import os
import re
import subprocess
import sys
from collections import Counter
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'images/creatures')
LANG_DIRS = {'uk': 'Українські', 'es': 'Español'}
THEMES = {'magic', 'nature', 'water', 'wind', 'cosmos', 'earth', 'tech', 'fire', 'sound', 'ice', 'shadow'}
# Rarity from the four ratings on the back (sum 256..376): legend ≥ 352 (16 cards), rare ≥ 341 (45 more).
LEGEND, RARE = 352, 341
# (suffix, width, height, quality)
SIZES = (('', 640, 960, 76), ('-b', 1024, 1536, 72), ('thumb', 320, 480, 64))


def js(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main(src):
    csvs = glob.glob(os.path.join(src, 'manifest*.csv'))
    if len(csvs) != 1:
        sys.exit('build-creatures: expected one manifest*.csv in ' + src)
    with open(csvs[0], encoding='utf-8-sig') as fh:
        rows = sorted(csv.DictReader(fh), key=lambda r: int(r['id']))
    assert [int(r['id']) for r in rows] == list(range(1, len(rows) + 1)), 'ids must be 1..N'
    files = {}  # (lang, n, side) -> png
    for lang, d in LANG_DIRS.items():
        for f in os.listdir(os.path.join(src, d)):
            m = re.match(r'(\d{3})_.+_0([12])_[^_]+\.png$', f)
            if m:
                files[(lang, int(m[1]), m[2])] = os.path.join(src, d, f)
    jobs, lines = [], []
    for r in rows:
        n = int(r['id'])
        cid = 'c%03d' % n
        assert r['theme'] in THEMES, (n, r['theme'])
        total = sum(int(r[k]) for k in ('rating_strength', 'rating_magic', 'rating_courage', 'rating_teamwork'))
        cat = 'legend' if total >= LEGEND else 'rare' if total >= RARE else 'common'
        for lang in LANG_DIRS:
            for side in '12':
                if (lang, n, side) not in files:
                    sys.exit('build-creatures: no %s side %s for %03d' % (lang, side, n))
            for suf, w, h, q in SIZES:
                s = files[(lang, n, '2' if suf == '-b' else '1')]
                out = os.path.join(OUT, lang, 'thumb', cid + '.webp') if suf == 'thumb' else os.path.join(OUT, lang, cid + suf + '.webp')
                if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(s):
                    jobs.append(['cwebp', '-quiet', '-q', str(q), '-resize', str(w), str(h), s, '-o', out])
        lines.append('  { id: %s, n: %d, cat: %s, el: %s, uk: %s, es: %s },' % (
            js(cid), n, js(cat), js(r['theme']), js(r['ua_name'].strip()), js(r['es_name'].strip())))
    for lang in LANG_DIRS:
        os.makedirs(os.path.join(OUT, lang, 'thumb'), exist_ok=True)
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as ex:
        for res in ex.map(lambda a: subprocess.run(a, check=False), jobs):
            if res.returncode:
                sys.exit('build-creatures: cwebp failed: ' + ' '.join(res.args))
    with open(os.path.join(ROOT, 'shared/creatures.js'), 'w', encoding='utf-8') as fh:
        fh.write('// Creature cards collection (generated by scripts/build-creatures.py — do not edit by hand).\n'
                 '// n = number printed on the card; cat: common | rare | legend (by the ratings on the back);\n'
                 '// el: element; uk/es = name. Images: images/creatures/<lang>/<id>.webp, <id>-b.webp (back), thumb/<id>.webp.\n'
                 'window.KF_CREATURES = [\n' + '\n'.join(lines) + '\n];\n')
    print(len(rows), 'creatures,', len(jobs), 'images built;', dict(Counter(l.split("cat: '")[1].split("'")[0] for l in lines)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    try:
        main(sys.argv[1])
    except (OSError, KeyError, ValueError) as e:
        sys.exit(f'build-creatures: {e}')
